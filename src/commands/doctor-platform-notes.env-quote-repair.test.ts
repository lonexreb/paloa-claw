// Doctor surfacing + prompt gate for the #103804 generated env quote repair.
import fs from "node:fs/promises";
import path from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { useAutoCleanupTempDirTracker } from "../../test/helpers/temp-dir.js";
import { resolveLaunchAgentEnvFilePath } from "../daemon/launchd-service-files.js";
import type { GatewayServiceEnv } from "../daemon/service-types.js";
import { maybeRepairMacGatewayServiceEnvQuotes } from "./doctor-platform-notes.js";
import type { DoctorPrompter } from "./doctor-prompter.js";

// Every test directory is tracked, so a test that makes two still cleans both.
const tempDirs = useAutoCleanupTempDirTracker(afterEach);
const makeStateDir = async () => await fs.realpath(tempDirs.make("openclaw-doctor-envfix-"));

function makePrompter(accept: boolean): DoctorPrompter {
  return { confirmRuntimeRepair: vi.fn(async () => accept) } as unknown as DoctorPrompter;
}

async function seedCorruptedEnvFile(
  label = "ai.openclaw.gateway",
): Promise<{ env: NodeJS.ProcessEnv; envFilePath: string }> {
  const env = { OPENCLAW_STATE_DIR: await makeStateDir() } as NodeJS.ProcessEnv;
  const envFilePath = resolveLaunchAgentEnvFilePath(env as GatewayServiceEnv, label);
  await fs.mkdir(path.dirname(envFilePath), { recursive: true });
  await fs.writeFile(
    envFilePath,
    [
      "# Generated by OpenClaw. Do not edit while the gateway service is installed.",
      `export AWS_REGION='"us-east-1"'`,
      "",
    ].join("\n"),
    { encoding: "utf8", mode: 0o600 },
  );
  return { env, envFilePath };
}

it("warns and repairs the corrupted env file when the operator accepts", async () => {
  const { env, envFilePath } = await seedCorruptedEnvFile();
  const noteFn = vi.fn();

  await maybeRepairMacGatewayServiceEnvQuotes({
    prompter: makePrompter(true),
    platform: "darwin",
    env,
    noteFn,
  });

  const texts = noteFn.mock.calls.map(([text]) => String(text));
  expect(texts.some((text) => text.includes("AWS_REGION") && text.includes("#103804"))).toBe(true);
  expect(texts.some((text) => text.includes("Rewrote 1 value(s)"))).toBe(true);
  expect(texts.some((text) => text.includes("openclaw gateway restart"))).toBe(true);
  expect(await fs.readFile(envFilePath, "utf8")).toContain("export AWS_REGION='us-east-1'");
});

it("names the node restart command after repairing the node service env file", async () => {
  const { env, envFilePath } = await seedCorruptedEnvFile("ai.openclaw.node");
  const noteFn = vi.fn();

  await maybeRepairMacGatewayServiceEnvQuotes({
    prompter: makePrompter(true),
    platform: "darwin",
    env,
    noteFn,
  });

  const texts = noteFn.mock.calls.map(([text]) => String(text));
  expect(texts.some((text) => text.includes("Rewrote 1 value(s)"))).toBe(true);
  // A gateway restart does not reload the node LaunchAgent env file.
  expect(texts.some((text) => text.includes("openclaw node restart"))).toBe(true);
  expect(texts.some((text) => text.includes("openclaw gateway restart"))).toBe(false);
  expect(await fs.readFile(envFilePath, "utf8")).toContain("export AWS_REGION='us-east-1'");
});

it("requires interactive confirmation so noninteractive --fix cannot auto-strip", async () => {
  const { env } = await seedCorruptedEnvFile();
  const prompter = makePrompter(true);

  await maybeRepairMacGatewayServiceEnvQuotes({
    prompter,
    platform: "darwin",
    env,
    noteFn: vi.fn(),
  });

  // The prompter contract: requiresInteractiveConfirmation blocks the
  // shouldAutoApproveDoctorFix shortcut and declines when prompting is
  // impossible, so an unattended doctor --fix never strips ambiguous values.
  expect(prompter.confirmRuntimeRepair).toHaveBeenCalledWith(
    expect.objectContaining({ requiresInteractiveConfirmation: true }),
  );
});

it("warns but leaves the file untouched when the operator declines", async () => {
  const { env, envFilePath } = await seedCorruptedEnvFile();
  const before = await fs.readFile(envFilePath, "utf8");
  const noteFn = vi.fn();

  await maybeRepairMacGatewayServiceEnvQuotes({
    prompter: makePrompter(false),
    platform: "darwin",
    env,
    noteFn,
  });

  const texts = noteFn.mock.calls.map(([text]) => String(text));
  expect(texts.some((text) => text.includes("#103804"))).toBe(true);
  expect(texts.some((text) => text.includes("Rewrote"))).toBe(false);
  expect(await fs.readFile(envFilePath, "utf8")).toBe(before);
});

it("stays silent off darwin and on clean installs", async () => {
  const { env } = await seedCorruptedEnvFile();
  const noteFn = vi.fn();
  await maybeRepairMacGatewayServiceEnvQuotes({
    prompter: makePrompter(true),
    platform: "linux",
    env,
    noteFn,
  });
  expect(noteFn).not.toHaveBeenCalled();

  await maybeRepairMacGatewayServiceEnvQuotes({
    prompter: makePrompter(true),
    platform: "darwin",
    env: { OPENCLAW_STATE_DIR: await makeStateDir() } as NodeJS.ProcessEnv,
    noteFn,
  });
  expect(noteFn).not.toHaveBeenCalled();
});
